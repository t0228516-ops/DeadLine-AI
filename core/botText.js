/** Орысша көпше түр: [1, 2–4, 5+] */
function ruPlural(count, forms) {
  const a = Math.abs(Number(count) || 0) % 100; const b = a % 10;
  if (a > 10 && a < 20) return forms[2];
  if (b > 1 && b < 5) return forms[1];
  if (b === 1) return forms[0];
  return forms[2];
}
