/** Хабар: bt('ru', 'paid', { credits, total }). Белгісіз тіл — қазақша; орысшасы жоқ кілт — қазақша. */
function bt(lang, key, params) {
  const d = lang === 'ru' ? RU : KK;
  const v = Object.prototype.hasOwnProperty.call(d, key) ? d[key] : KK[key];
  if (v === undefined) throw new Error('botText: unknown key ' + key);
  return typeof v === 'function' ? v(params || {}) : v;
}

/** Мәзір батырмасы (екі тілде де) → әрекет */
const MENU_KEYS = ['kb_app', 'kb_quiz', 'kb_buy', 'kb_balance', 'kb_ref', 'kb_partner', 'kb_help'];
const MENU_ACTION = new Map();
for (const d of [KK, RU]) for (const k of MENU_KEYS) MENU_ACTION.set(d[k], k.slice(3));
MENU_ACTION.set('📝 Тақырып жазу', 'legacy');   // ескі пернетақта (чатта генерация жоқ)
const menuAction = (text) => (text && MENU_ACTION.get(text)) || null;

/** Негізгі мәзір (тілге қарай) */
function mainKeyboard(lang) {
  const t = (k) => ({ text: bt(lang, k) });
  return {
    reply_markup: {
      keyboard: [[t('kb_app'), t('kb_quiz')], [t('kb_buy'), t('kb_balance')], [t('kb_ref'), t('kb_partner')], [t('kb_help')]],
      resize_keyboard: true,
      persistent: true,
    },
    parse_mode: 'Markdown',
  };
}

