  /** Бір тілдің аудармашысы (бетте — сақталған тіл; тестте — кез келгені) */
  function make(lang) {
    const ru = lang === 'ru';
    /** Мәтін: орысша интерфейсте — сөздіктен; {n} орындары толтырылады */
    const t = (s, v) => fill(ru && has(s) ? RU[s] : s, v);
    /** Санға байланған сөз (кілт — қазақша сөз, PLURAL_RU-да болуы керек) */
    const n = (count, kk) => {
      if (!ru) return kk;
      const f = PLURAL_RU[kk];
      return f ? ruPlural(count, f) : t(kk);
    };
    /** Серверден келген мәтін: аудармасы бар болса — аударма; орысша интерфейсте аудармасыз қазақша жол — '' (көрсетілмейді) */
    const srv = (s) => {
      if (s == null || s === '') return '';
      const str = String(s);
      if (!ru) return str;
      if (has(str)) return RU[str];
      for (const [re, to] of RU_PATTERNS) if (re.test(str)) return str.replace(re, to);
      return KK_ONLY.test(str) ? '' : str;
    };
    /** Сервер қатесінің хабары (data = жауап денесі) */
    const errText = (data, fallback) => {
      const d = data || {};
      if (ru) return (d.error && ERR_RU[d.error]) || srv(d.message) || (fallback ? t(fallback) : '');
      return d.message || (fallback ? t(fallback) : '');
    };
    /** HTML-ді бір рет аудару (тек орысша интерфейсте) */
    const apply = (root) => {
      if (!ru || !root) return;
      for (const it of collect(root)) {
        if (!has(it.key)) continue;
        const v = RU[it.key];
        if (it.kind === 'text') {
          const raw = it.node.nodeValue;
          it.node.nodeValue = raw.match(/^\s*/)[0] + v + raw.match(/\s*$/)[0];
        } else if (it.kind === 'attr') it.node.setAttribute(it.attr, v);
        else it.node.innerHTML = v;
      }
    };
    return { lang: ru ? 'ru' : 'kk', t, n, srv, errText, apply };
  }

